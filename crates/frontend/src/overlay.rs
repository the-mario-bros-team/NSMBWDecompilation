/// Text at (x, y) with pixel size `px`; runs of lit pixels in a row become
/// one rectangle. Returns the width drawn.
pub fn text(out: &mut Vec<OverlayRect>, x: i32, y: i32, px: i32, color: u8, s: &str) -> i32 {
    for (i, c) in s.chars().enumerate() {
        let gx = x + i as i32 * 6 * px;
        for (row, bits) in glyph(c).iter().enumerate() {
            let mut col = 0;
            while col < 5 {
                if bits & (0x10 >> col) == 0 {
                    col += 1;
                    continue;
                }
                let start = col;
                while col < 5 && bits & (0x10 >> col) != 0 {
                    col += 1;
                }
                out.push(OverlayRect { x: gx + start * px, y: y + row as i32 * px, w: (col - start) * px, h: px, color });
            }
        }
    }
    s.chars().count() as i32 * 6 * px
}

/// A block of text lines on a dark backdrop at (x, y).
pub fn panel(out: &mut Vec<OverlayRect>, x: i32, y: i32, px: i32, lines: &[(u8, String)]) -> (i32, i32) {
    let w = lines.iter().map(|(_, l)| l.chars().count() as i32).max().unwrap_or(0) * 6 * px + 4 * px;
    let h = lines.len() as i32 * 9 * px + 3 * px;
    out.push(OverlayRect { x, y, w, h, color: BACKDROP });
    for (i, (color, line)) in lines.iter().enumerate() {
        text(out, x + 2 * px, y + 2 * px + i as i32 * 9 * px, px, *color, line);
    }
    (w, h)
}

/// Frame-time bars (milliseconds), green within `budget_ms`, yellow within
/// twice that, red beyond; the line marks the budget.
pub fn graph(out: &mut Vec<OverlayRect>, x: i32, y: i32, px: i32, times: &[f32], budget_ms: f32) {
    let (bar, height) = (px.max(1), 40 * px);
    let w = times.len() as i32 * bar;
    out.push(OverlayRect { x, y, w, h: height, color: BACKDROP });
    let scale = height as f32 / (budget_ms * 3.0).max(1.0);
    for (i, &t) in times.iter().enumerate() {
        let h = ((t * scale) as i32).clamp(1, height);
        let color = if t <= budget_ms * 1.05 {
            GREEN
        } else if t <= budget_ms * 2.0 {
            YELLOW
        } else {
            RED
        };
        out.push(OverlayRect { x: x + i as i32 * bar, y: y + height - h, w: bar, h, color });
    }
    let line = y + height - (budget_ms * scale) as i32;
    out.push(OverlayRect { x, y: line, w, h: 1, color: GREY });
}

#[cfg(test)]
mod tests {
    #[test]
    fn text_merges_runs() {
        let mut v = Vec::new();
        let w = super::text(&mut v, 0, 0, 2, 0, "-");
        assert_eq!(w, 12);
        assert_eq!(v.len(), 1);
        assert_eq!((v[0].w, v[0].h, v[0].y), (10, 2, 6));
    }
}
