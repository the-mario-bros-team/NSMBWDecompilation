#!/usr/bin/env node
// Compute translated-vs-total progress from the ledger and Ghidra indexes.
// Usage: node tools/progress.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const ledgerPath = path.join(root, 'ledger', 'functions.csv');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.length > 1 || r[0] !== '');
}

const rows = parseCsv(fs.readFileSync(ledgerPath, 'utf8'));
const header = rows[0];
const idx = Object.fromEntries(header.map((h, i) => [h, i]));
const translated = new Set(rows.slice(1).map((r) => parseInt(r[idx.address], 16)));

const buckets = [
  { name: 'main.dol', total: 10276, test: (a) => a >= 0x80000000 && a < 0x80500000 },
  { name: 'd_profileNP', total: 36, test: (a) => a >= 0x80500000 && a < 0x80600000 },
  { name: 'd_basesNP', total: 5615, test: (a) => a >= 0x80600000 && a < 0x80A00000 },
  { name: 'd_enemiesNP', total: 3555, test: (a) => a >= 0x80A00000 && a < 0x80C00000 },
  { name: 'd_en_bossNP', total: 770, test: (a) => a >= 0x80C00000 && a < 0x81000000 },
];

const result = buckets.map((b) => {
  const got = [...translated].filter(b.test).length;
  return { ...b, got, pct: +((got / b.total) * 100).toFixed(2) };
});
const total = result.reduce((a, b) => ({ total: a.total + b.total, got: a.got + b.got }), { total: 0, got: 0 });

const lines = [
  '# Progress',
  '',
  'Generated by `tools/progress.mjs` from `ledger/functions.csv` and the Ghidra',
  'function indexes. "Translated" means a function has at least one Rust',
  'translation recorded; it does not mean the whole module is complete.',
  '',
  '| Module | Translated | Total | Percent |',
  '|---|---:|---:|---:|',
  ...result.map((r) => `| ${r.name} | ${r.got} | ${r.total} | ${r.pct}% |`),
  `| **total** | **${total.got}** | **${total.total}** | **${((total.got / total.total) * 100).toFixed(2)}%** |`,
  '',
  '## Remaining work',
  '',
  `- ${total.total - total.got} functions have no Rust translation yet.`,
  '- Per-range/semantic targets: `docs/COVERAGE*.md` and `docs/FUNCTION_INDEX.md`.',
  '- Asset and port work is independent of this count; see `docs/PORT_WINDOWS.md`.',
  '',
];
fs.writeFileSync(path.join(root, 'docs', 'PROGRESS.md'), lines.join('\n'));
console.log(JSON.stringify({ result, total }, null, 2));
