#!/usr/bin/env node
// Gap report: which functions in each Ghidra export still have no Rust row?
//
// Inputs:
//   work/ghidra/<export>/export/functions.tsv
//   ledger/functions.csv
// Output:
//   docs/GAP_REPORT.md  (generated; do not hand-edit)
//
// Buckets are 64 KiB windows of the analysis address space. For REL modules the
// addresses are synthetic analysis addresses (see docs/REL2ELF.md), not runtime
// addresses.

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(process.argv[2] ?? '.');
const exports = [
  ['main.dol', 'work/ghidra/main-gb/export'],
  ['d_profileNP', 'work/ghidra/rel-d_profileNP/export'],
  ['d_basesNP', 'work/ghidra/rel-d_basesNP/export'],
  ['d_enemiesNP', 'work/ghidra/rel-d_enemiesNP/export'],
  ['d_en_bossNP', 'work/ghidra/rel-d_en_bossNP/export'],
];

const ledgerPath = path.join(root, 'ledger/functions.csv');
const ledger = fs.readFileSync(ledgerPath, 'utf8').trim().split(/\r?\n/).slice(1);
const known = new Set();
for (const line of ledger) {
  const cols = line.match(/("([^"]|"")*"|[^,]*)(,|$)/g);
  if (!cols) continue;
  const cells = cols.map((c) => c.replace(/,$/, '').replace(/^"|"$/g, '').replace(/""/g, '"'));
  let address = (cells[1] ?? '').trim().toLowerCase().replace(/^0x/, '');
  // Ledger rows for multi-address helpers may store a range (start-end);
  // the Ghidra export keys on the entry address.
  address = address.split('-')[0].trim();
  if (address) known.add(address);
}

function parseTsv(file) {
  const lines = fs.readFileSync(file, 'utf8').trim().split(/\r?\n/);
  const header = lines.shift().split('\t');
  const iAddr = header.indexOf('address');
  const iName = header.indexOf('name');
  const iSize = header.indexOf('size');
  const rows = [];
  for (const line of lines) {
    const cells = line.split('\t');
    const address = (cells[iAddr] ?? '').trim().toLowerCase();
    if (!address) continue;
    rows.push({
      address,
      name: (cells[iName] ?? '').trim(),
      size: Number(cells[iSize] ?? 0) || 0,
    });
  }
  return rows;
}

const out = [];
out.push('# Gap report');
out.push('');
out.push('Generated by `node tools/gap-report.mjs`. Buckets are 64 KiB analysis-');
out.push('address windows. REL addresses are synthetic analysis addresses, not');
out.push('runtime addresses (see `docs/REL2ELF.md`).');
out.push('');
out.push('| Export | Translated | Total | Remaining | Bytes remaining |');
out.push('|---|---:|---:|---:|---:|');

const details = [];
for (const [label, dir] of exports) {
  const tsv = path.join(root, dir, 'functions.tsv');
  if (!fs.existsSync(tsv)) continue;
  const rows = parseTsv(tsv);
  let translated = 0;
  let bytes = 0;
  const buckets = new Map();
  for (const row of rows) {
    if (known.has(row.address)) {
      translated++;
      continue;
    }
    bytes += row.size;
    const value = parseInt(row.address, 16);
    if (Number.isNaN(value)) continue;
    const base = Math.floor(value / 0x10000) * 0x10000;
    const key = base.toString(16).padStart(8, '0');
    const b = buckets.get(key) ?? { count: 0, bytes: 0, examples: [] };
    b.count++;
    b.bytes += row.size;
    if (b.examples.length < 3 && row.size >= 16) {
      b.examples.push(`${row.address} (${row.name}, ${row.size} B)`);
    }
    buckets.set(key, b);
  }
  out.push(`| ${label} | ${translated} | ${rows.length} | ${rows.length - translated} | ${bytes} |`);
  const top = [...buckets.entries()].sort((a, b) => b[1].bytes - a[1].bytes).slice(0, 12);
  details.push([label, top]);
}

out.push('');
for (const [label, top] of details) {
  out.push(`## ${label}`);
  out.push('');
  out.push('| Bucket | Untranslated | Bytes | Examples |');
  out.push('|---|---:|---:|---|');
  for (const [base, b] of top) {
    out.push(`| 0x${base} | ${b.count} | ${b.bytes} | ${b.examples.join('; ')} |`);
  }
  out.push('');
}

const dest = path.join(root, 'docs/GAP_REPORT.md');
fs.writeFileSync(dest, out.join('\n') + '\n');
console.log(JSON.stringify({ out: dest, exports: details.length }, null, 2));
